#!/usr/bin/env python3
"""Regenerates js/search-index.js from the site's HTML pages.
Run from the site root after editing page content:  python3 tools/build-search-index.py
Page list/titles come from the `pages` array in js/search.js (single source of truth for titles);
this script only adds searchable body text (English + French) per page."""
import re, json, sys, pathlib
from bs4 import BeautifulSoup, NavigableString
root = pathlib.Path(__file__).resolve().parent.parent
src = (root/'js/search.js').read_text(encoding='utf-8')
urls = re.findall(r"\['[^\]]*?','[^\]]*?','[^\]]*?','([^']+\.html(?:#[^']*)?)'\]", src)
seen=[]; [seen.append(u) for u in urls if u not in seen]
def clean(s): return re.sub(r'\s+',' ',s).strip()
index={}
for u in seen:
    path,_,frag=u.partition('#')
    soup=BeautifulSoup((root/path).read_text(encoding='utf-8'),'html.parser')
    main=soup.find('main') or soup.body
    if frag:  # in-page section entry: the section plus the two sections that follow it
        sec=main.find(id=frag); parts=[sec]+list(sec.find_next_siblings('section',limit=2))
        main=BeautifulSoup('<div>'+''.join(str(x) for x in parts)+'</div>','html.parser')
    for c in main.select('.crumb'): c.decompose()
    en=[];fr=[];done=set()
    for node in main.find_all(string=True):
        if not isinstance(node,NavigableString) or node.parent.name in ('script','style','svg','title'): continue
        t=clean(str(node))
        if not t: continue
        anc=node.find_parent(lambda x: x.has_attr('data-en') and x.has_attr('data-fr'))
        if anc is not None:
            if id(anc) in done: continue
            done.add(id(anc)); en.append(clean(anc['data-en'])); fr.append(clean(anc['data-fr']))
        else:
            en.append(t); fr.append(t)
    desc=soup.find('meta',attrs={'name':'description'})
    index[u]={'en':' '.join(dict.fromkeys(en)),'fr':' '.join(dict.fromkeys(fr)),'desc':clean(desc['content']) if desc else ''}
out='/* Generated by tools/build-search-index.py — do not edit by hand. */\nwindow.QARTEXA_SEARCH_INDEX='+json.dumps(index,ensure_ascii=False,separators=(',',':'))+';\n'
(root/'js/search-index.js').write_text(out,encoding='utf-8')
print(len(index),'pages indexed,',len(out)//1024,'KB')
